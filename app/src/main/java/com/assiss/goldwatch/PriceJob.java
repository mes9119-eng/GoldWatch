package com.assiss.goldwatch;

import android.app.job.JobInfo;
import android.app.job.JobParameters;
import android.app.job.JobScheduler;
import android.app.job.JobService;
import android.content.ComponentName;
import android.content.Context;

/** Runs every ~15 minutes (Android's minimum) to refresh price and check alerts. */
public class PriceJob extends JobService {
    static final int ID = 1001;

    @Override
    public boolean onStartJob(final JobParameters params) {
        new Thread(() -> {
            Updater.run(getApplicationContext());
            jobFinished(params, false);
        }).start();
        return true;
    }

    @Override
    public boolean onStopJob(JobParameters params) {
        return true;
    }

    static void schedule(Context c) {
        JobScheduler js = c.getSystemService(JobScheduler.class);
        if (js == null || js.getPendingJob(ID) != null) return;
        JobInfo info = new JobInfo.Builder(ID, new ComponentName(c, PriceJob.class))
                .setRequiredNetworkType(JobInfo.NETWORK_TYPE_ANY)
                .setPeriodic(15 * 60 * 1000L)
                .setPersisted(true)
                .build();
        js.schedule(info);
    }
}
